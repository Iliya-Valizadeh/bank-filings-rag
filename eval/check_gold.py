"""Script checks for the answer key. They catch wrong page numbers; they are not a reading.

Two checks, both on the pages each question proposes:

1. Answer text (all questions with `answer_any`): does the page's text contain one of
   the answer strings?
2. Label and figure together (questions with `check_label` and `check_figure`, i.e.
   11 to 30): do a label (e.g. "Total PCL") and the figure (e.g. "3,232") appear in the
   same passage? A passage is one PyMuPDF layout block: a paragraph, a heading, or a
   table body. The result is "together" when they are in the same block and at most
   MAX_GAP characters apart, "same block, far apart" when the gap is larger, and
   "not together" otherwise. This rules out a page that has the figure somewhere
   unrelated to the question.

A question that passes both checks keeps "verified": false and "verified_by": "script"
until someone reads the page.

Run:  python -m eval.check_gold --pdf data/raw/rbc_2024.pdf
Writes eval/gold_check.md. Exits with status 1 if any page check fails.
"""
from __future__ import annotations
import argparse
import json
import re
from pathlib import Path

from src import ingest
from eval.metrics import contains_answer, normalize

GOLD = Path(__file__).parent / "gold_qa.jsonl"
MAX_GAP = 200


def figure_pattern(figure: str) -> str:
    """Match a figure without matching inside a longer number: "729" must not match
    "1,729" or "7290". A figure that contains letters ("net-zero emissions by 2050") only
    gets the leading guard, because the PDF text often runs a footnote marker straight
    into the last word ("20503" is "2050" followed by footnote 3)."""
    core = re.escape(normalize(figure))
    lead = r"(?<![\d.,])"
    if re.search(r"[a-z]", figure, re.I):
        return lead + core
    return lead + core + r"(?!\d|[.,]\d)"


def label_figure_gap(blocks: list[str], labels, figures) -> int | None:
    """Smallest character gap between a label and a figure in the same block."""
    best = None
    for block in blocks:
        text = normalize(block)
        lab = [m.start() for lab_ in labels for m in re.finditer(re.escape(normalize(lab_)), text)]
        fig = [m.start() for f in figures for m in re.finditer(figure_pattern(f), text)]
        for a in lab:
            for b in fig:
                if best is None or abs(a - b) < best:
                    best = abs(a - b)
    return best


def describe(gap):
    if gap is None:
        return "not together"
    return f"together ({gap} chars)" if gap <= MAX_GAP else f"same block, far apart ({gap} chars)"


def check(pdf_path) -> list[dict]:
    pages = {p["page"]: p for p in ingest.load_pages(pdf_path)}
    rows = [json.loads(line) for line in GOLD.read_text(encoding="utf-8").splitlines()
            if line.strip()]
    out = []
    for r in rows:
        rec = {"id": r["id"], "verified_by": r.get("verified_by"), "pages": {}, "strict": {}}
        if r.get("answer_any"):
            rec["pages"] = {p: contains_answer(pages.get(p, {}).get("text", ""), r["answer_any"])
                            for p in r["source_pages"]}
            rec["status"] = "ok" if any(rec["pages"].values()) else "FAIL"
        else:
            rec["status"] = "no answer strings, not checkable"
        if r.get("check_label"):
            gaps = {p: label_figure_gap(pages.get(p, {}).get("blocks", []),
                                        r["check_label"], r["check_figure"])
                    for p in r["source_pages"]}
            rec["strict"] = gaps
            ok = any(g is not None and g <= MAX_GAP for g in gaps.values())
            rec["strict_status"] = "ok" if ok else "CHECK BY HAND"
            rec["label"] = r["check_label"][0]
            rec["figure"] = r["check_figure"][0]
        out.append(rec)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pdf", required=True)
    a = ap.parse_args()
    res = check(a.pdf)
    lines = ["# Answer-key page checks", "",
             "Generated by `python -m eval.check_gold`. These are script checks. They catch a "
             "wrong page number but are no substitute for reading the page.", "",
             "## Check 1: the page contains the answer text", "",
             "| id | verified by | status | pages (contains answer?) |", "|---|---|---|---|"]
    for r in res:
        pages = ", ".join(f"p{p}: {'yes' if ok else 'no'}" for p, ok in r["pages"].items())
        lines.append(f"| {r['id']} | {r.get('verified_by') or '-'} | {r['status']} | {pages} |")
    lines += ["", "## Check 2: label and figure in the same passage (questions 11 to 30)", "",
              "A passage is one layout block from PyMuPDF. \"Together\" means the label and the "
              f"figure are in the same block and at most {MAX_GAP} characters apart.", "",
              "| id | label | figure | status | per page |", "|---|---|---|---|---|"]
    for r in res:
        if not r["strict"]:
            continue
        per = ", ".join(f"p{p}: {describe(g)}" for p, g in r["strict"].items())
        lines.append(f"| {r['id']} | {r['label']} | {r['figure']} | {r['strict_status']} | {per} |")
    Path(__file__).with_name("gold_check.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    if any(r["status"] == "FAIL" for r in res):
        raise SystemExit(1)


if __name__ == "__main__":
    main()
