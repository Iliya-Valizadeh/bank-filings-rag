"""Script check for the answer key: does each proposed page contain the answer?

For every question with answer strings (answer_any), look at the PDF text of each page
in source_pages and report whether one of the strings is on it. This catches a wrong
page number. It cannot tell whether the question is well posed or whether the answer
text is right, which is why questions checked only by this script stay
"verified": false until I read the page myself.

Run:  python -m eval.check_gold --pdf data/raw/rbc_2024.pdf
Writes eval/gold_check.md.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

from src import ingest
from eval.metrics import contains_answer

GOLD = Path(__file__).parent / "gold_qa.jsonl"


def check(pdf_path) -> list[dict]:
    pages = {p["page"]: p["text"] for p in ingest.load_pages(pdf_path, with_blocks=False)}
    rows = [json.loads(line) for line in GOLD.read_text(encoding="utf-8").splitlines() if line.strip()]
    out = []
    for r in rows:
        if not r.get("answer_any"):
            out.append({"id": r["id"], "status": "no answer strings, not checkable", "pages": {},
                        "verified": r.get("verified"), "verified_by": r.get("verified_by")})
            continue
        per_page = {p: contains_answer(pages.get(p, ""), r["answer_any"]) for p in r["source_pages"]}
        status = "ok" if any(per_page.values()) else "FAIL"
        out.append({"id": r["id"], "status": status, "pages": per_page,
                    "verified": r.get("verified"), "verified_by": r.get("verified_by")})
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pdf", required=True)
    a = ap.parse_args()
    res = check(a.pdf)
    lines = ["# Answer-key page check", "",
             "Generated by `python -m eval.check_gold`. A page is `yes` when its text contains "
             "one of the question's answer strings.", "",
             "| id | verified by | status | pages (contains answer?) |", "|---|---|---|---|"]
    for r in res:
        pages = ", ".join(f"p{p}: {'yes' if ok else 'no'}" for p, ok in r["pages"].items())
        lines.append(f"| {r['id']} | {r.get('verified_by') or '-'} | {r['status']} | {pages} |")
    Path(__file__).with_name("gold_check.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    if any(r["status"] == "FAIL" for r in res):
        raise SystemExit(1)


if __name__ == "__main__":
    main()
